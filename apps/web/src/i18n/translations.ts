export type Lang = "en" | "bn";

const dictionaries: Record<Lang, Translations> = { en, bn };

/** Dot-path lookup — "wallet.couponLabel" etc. Falls back to the key itself (with a console warning) if it doesn't resolve, so a typo never blanks the UI. */
function resolve(dict: Translations, path: string): string | undefined {
  const parts = path.split(".");
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let node: any = dict;
  for (const part of parts) {
    if (node == null || typeof node !== "object") return undefined;
    node = node[part];
  }
  return typeof node === "string" ? node : undefined;
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const value = resolve(dictionaries[lang], key) ?? resolve(dictionaries.en, key);
  if (value === undefined) {
    if (import.meta.env.DEV) console.warn(`Missing translation key: ${key}`);
    return key;
  }
  if (!vars) return value;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{{${k}}}`, String(v)), value);
}
